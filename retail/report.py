"""Render RESULTS.md, MEMO.md, DATA_QUALITY.md and the README headline from results.json.

Every figure in the generated text is formatted from the results dict (which is a SELECT from
the mart tables). The only literals are thresholds and the three scenario assumptions, and the
memo names them as assumptions."""

from __future__ import annotations

import re
from pathlib import Path

from retail.plots import gbp, pct

HEADLINE_START = "<!-- HEADLINE:START -->"
HEADLINE_END = "<!-- HEADLINE:END -->"


def _signed_gbp(x: float) -> str:
    return ("+" if x >= 0 else "-") + gbp(abs(x))


def _num(x: float, digits: int = 0) -> str:
    return f"{x:,.{digits}f}"


def _table(headers: list[str], rows: list[list[str]], align: list[str] | None = None) -> str:
    align = align or ["l"] + ["r"] * (len(headers) - 1)
    sep = ["---:" if a == "r" else ":---" for a in align]
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(sep) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _targeted(res: dict) -> list[dict]:
    t = [s for s in res["segments"] if s["is_targeted"]]
    return sorted(t, key=lambda s: -s["revenue_at_risk_next_quarter"])


def _case(res: dict, name: str) -> dict:
    return next(r for r in res["scenario"] if r["case_name"] == name)


def _join(names: list[str]) -> str:
    if len(names) <= 1:
        return "".join(names)
    return ", ".join(names[:-1]) + " and " + names[-1]


def headline_block(res: dict) -> str:
    h, si = res["headline"], res["scenario_inputs"]
    tg = _targeted(res)
    low, high = _case(res, "low"), _case(res, "high")
    y1 = next(r for r in res["yoy"] if r["sort_order"] == 4)
    drivers = {r["driver"]: r for r in res["yoy"] if r["sort_order"] < 4}
    biggest = max(drivers.values(), key=lambda r: abs(r["revenue_effect"]))
    m1 = next(r for r in res["retention_curve"] if r["month_offset"] == 1)
    top = max(res["segments"], key=lambda s: s["revenue_share"])
    lines = [
        HEADLINE_START,
        f"**Setup.** {_num(h['raw_rows'])} transaction lines from a UK online gift-ware retailer ({h['window_start']} to {h['window_end']}, 24 complete months). "
        f"After cleaning, {_num(h['kept_rows'])} lines ({pct(h['kept_rows'] / h['raw_rows'], 0)}) feed the KPIs. Revenue is net of returns and is not profit.",
        "",
        f"- **Revenue:** {gbp(h['net_revenue'])} net revenue over the 24 months. The second year is {pct(abs(h['yoy_growth']))} {'higher' if h['yoy_growth'] >= 0 else 'lower'} than the first. "
        f"Among customers with an ID the change is {gbp(y1['revenue_effect'])}, and {biggest['driver'].lower()} is the largest driver ({gbp(biggest['revenue_effect'])}).",
        f"- **Seasonality:** September to November brings {pct(h['sepnov_share_year2'], 0)} of the second year's revenue.",
        f"- **Retention:** {pct(h['one_order_share'], 0)} of customers bought once. About {pct(m1['retention_rate'], 0)} of a new cohort buys again the next month.",
        f"- **Concentration:** the top 10% of customers hold {pct(h['top_decile_revenue_share'], 0)} of revenue; {top['segment']} are {pct(top['customer_share'], 0)} of customers and {pct(top['revenue_share'], 0)} of revenue.",
        f"- **Recommendation:** target {_join([s['segment'] for s in tg])} ({_num(si['targeted_customers'])} customers, {pct(si['targeted_share_of_at_risk'], 0)} of the {gbp(si['total_revenue_at_risk'])} revenue at risk next quarter). "
        f"Scenario only: lowering their lapse rate by {pct(low['lapse_reduction'], 0)} to {pct(high['lapse_reduction'], 0)} would protect {gbp(low['recovered_revenue_pooled_rates'])} to {gbp(high['recovered_revenue'])} of revenue.",
        HEADLINE_END,
    ]
    return "\n".join(lines)


def update_readme(readme: Path, res: dict) -> bool:
    text = readme.read_text(encoding="utf-8")
    block = headline_block(res)
    pattern = re.compile(re.escape(HEADLINE_START) + r".*?" + re.escape(HEADLINE_END), re.S)
    if not pattern.search(text):
        return False
    readme.write_text(pattern.sub(lambda _m: block, text), encoding="utf-8")
    return True


def results_md(res: dict) -> str:
    h, si = res["headline"], res["scenario_inputs"]
    note = (
        "> **Fixture run.** These numbers come from a small synthetic file used for tests and CI, not from the real dataset.\n\n"
        if res.get("fixture")
        else ""
    )
    out = [
        "# Results",
        "",
        "Generated by `retail report` from `results.json`, which is read from the mart tables. Do not edit by hand.",
        "",
        note,
    ]

    out += ["## Headline KPIs", ""]
    out.append(
        _table(
            ["Metric", "Value"],
            [
                ["Window", f"{h['window_start']} to {h['window_end']} (24 complete months)"],
                ["Raw rows", _num(h["raw_rows"])],
                [
                    "Rows kept after cleaning",
                    f"{_num(h['kept_rows'])} ({pct(h['kept_rows'] / h['raw_rows'])})",
                ],
                ["Net revenue (sales minus returns)", gbp(h["net_revenue"], 1)],
                ["Sales revenue", gbp(h["sales_revenue"], 1)],
                ["Returns", f"{gbp(h['returns_value'], 1)} ({pct(h['return_rate'])} of sales)"],
                ["Net revenue, year 1 (Dec 2009 to Nov 2010)", gbp(h["net_revenue_year1"], 1)],
                ["Net revenue, year 2 (Dec 2010 to Nov 2011)", gbp(h["net_revenue_year2"], 1)],
                ["Year-on-year change", f"{h['yoy_growth'] * 100:+.1f}%"],
                ["Orders (sale invoices)", _num(h["orders"])],
                [
                    "Mean and median order value",
                    f"{gbp(h['mean_order_value'])} and {gbp(h['median_order_value'])}",
                ],
                ["Identified customers", _num(h["customers"])],
                ["Guest checkout share of revenue", pct(h["guest_revenue_share"])],
                ["Customers who bought once", pct(h["one_order_share"])],
                ["Median orders per customer", _num(h["median_orders_per_customer"])],
                [
                    "Median days between orders (customer average)",
                    _num(h["median_days_between_orders"]),
                ],
                ["Top 10% of customers, share of revenue", pct(h["top_decile_revenue_share"])],
                ["Largest customer, share of revenue", pct(h["top1_customer_share"])],
                ["Top 20 products, share of revenue", pct(h["top20_products_share"])],
                [f"{h['top_country']}, share of revenue", pct(h["top_country_share"])],
                [
                    "September to November share of revenue, year 1 and year 2",
                    f"{pct(h['sepnov_share_year1'])} and {pct(h['sepnov_share_year2'])}",
                ],
            ],
        )
    )

    out += [
        "",
        "## Cleaning: raw rows to kept rows",
        "",
        "Each rule is applied in order and a row is removed by the first rule that matches. Details and decisions: [DATA_QUALITY.md](DATA_QUALITY.md).",
        "",
    ]
    out.append(
        _table(
            ["Step", "Rows", "Revenue (quantity x price)"],
            [
                [
                    b["label"].replace("_", " "),
                    f"{b['n_rows']:+,}" if b["step"] not in (0, 99) else _num(b["n_rows"]),
                    gbp(b["revenue"], 1),
                ]
                for b in res["bridge"]
            ],
        )
    )

    out += ["", "## Question 1: revenue trend and drivers", ""]
    out.append(
        _table(
            ["Driver", "Year 1", "Year 2", "Effect on revenue"],
            [
                [
                    r["driver"],
                    _num(r["year1_value"], 2 if r["sort_order"] == 2 else 0),
                    _num(r["year2_value"], 2 if r["sort_order"] == 2 else 0),
                    gbp(r["revenue_effect"]),
                ]
                for r in res["yoy"]
            ],
        )
    )
    out += [
        "",
        "Revenue for identified customers equals active customers x orders per customer x net revenue per order. The effects use a log-mean split and add up to the total change exactly.",
        "",
    ]
    out.append(
        _table(
            ["Country", "Net revenue", "Share", "Customers", "Year-on-year"],
            [
                [
                    c["country"],
                    gbp(c["net_revenue"]),
                    pct(c["revenue_share"]),
                    _num(c["customers"]),
                    f"{c['yoy_growth'] * 100:+.0f}%" if c["yoy_growth"] is not None else "n/a",
                ]
                for c in res["countries"]
            ],
        )
    )
    out += [""]
    out.append(
        _table(
            ["Product", "Description", "Net revenue", "Return rate"],
            [
                [p["stock_code"], p["description"], gbp(p["net_revenue"]), pct(p["return_rate"])]
                for p in res["products"]
            ],
            ["l", "l", "r", "r"],
        )
    )
    out += ["", "Highest return rates among products with at least £20k of sales:", ""]
    out.append(
        _table(
            ["Product", "Description", "Sales", "Return rate"],
            [
                [p["stock_code"], p["description"], gbp(p["sales_revenue"]), pct(p["return_rate"])]
                for p in res["high_return_products"]
            ],
            ["l", "l", "r", "r"],
        )
    )

    out += ["", "## Question 2: cohort retention", ""]
    out.append(
        _table(
            [
                "Months after first purchase",
                "Cohorts observed",
                "Customers",
                "Buying that month",
                "Retention",
            ],
            [
                [
                    str(r["month_offset"]),
                    str(r["cohorts_observed"]),
                    _num(r["customers"]),
                    _num(r["active_customers"]),
                    pct(r["retention_rate"]),
                ]
                for r in res["retention_curve"]
                if r["month_offset"] in (1, 2, 3, 6, 9, 12, 18)
            ],
        )
    )
    out += [
        "",
        "The December 2009 cohort is excluded because it mixes new customers with people who were already buying before the file starts.",
        "",
    ]

    out += [
        "## Question 3: RFM segments and churn risk",
        "",
        f"Live segmentation on {res['params']['current_snapshot']}. Lapse rates are measured: for each back-test snapshot, the share of a segment that did not buy in the following 3 months. The base case uses the same-season snapshot (1 December 2010, the quarter December to February).",
        "",
    ]
    out.append(
        _table(
            [
                "Segment",
                "Customers",
                "Revenue share",
                "Lapse rate (winter)",
                "95% CI",
                "Lapse range, 5 quarters",
                "Revenue at risk",
                "Targeted",
            ],
            [
                [
                    s["segment"],
                    _num(s["customers"]),
                    pct(s["revenue_share"]),
                    pct(s["same_season_lapse_rate"]),
                    f"{pct(s['lapse_ci_low'])} to {pct(s['lapse_ci_high'])}",
                    f"{pct(1 - s['repurchase_rate_max'])} to {pct(1 - s['repurchase_rate_min'])}",
                    gbp(s["revenue_at_risk_next_quarter"]),
                    "yes" if s["is_targeted"] else "no",
                ]
                for s in sorted(res["segments"], key=lambda s: -s["revenue_at_risk_next_quarter"])
            ],
        )
    )
    out += [
        "",
        f"Base: {_num(si['base_customers'])} identified customers with {gbp(si['base_trailing_12m_net_revenue'])} of net revenue in the last 12 months (quarterly run-rate {gbp(si['base_quarterly_run_rate'])}). "
        f"Revenue at risk next quarter is {gbp(si['total_revenue_at_risk'])} ({pct(si['at_risk_share_of_run_rate'], 0)} of the run-rate). "
        f"The expected next-quarter revenue from today's customers, if nothing is done, is {gbp(si['expected_next_q_revenue_do_nothing'])} using last winter's behaviour.",
        "",
        "### Scenario (assumption-driven, not measured)",
        "",
        "The data has no campaign, cost or margin. The lapse reductions below are assumptions; revenue is not profit.",
        "",
    ]
    out.append(
        _table(
            [
                "Assumed lapse reduction",
                "Customers contacted",
                "Revenue protected (winter rates)",
                "Revenue protected (all-season rates)",
                "Per customer contacted",
            ],
            [
                [
                    pct(r["lapse_reduction"], 0),
                    _num(r["customers_contacted"]),
                    gbp(r["recovered_revenue"]),
                    gbp(r["recovered_revenue_pooled_rates"]),
                    f"£{r['recovered_revenue_per_contact']:.2f}",
                ]
                for r in res["scenario"]
            ],
        )
    )
    out += [""]
    return "\n".join(out).replace("\n\n\n", "\n\n") + "\n"


def memo_md(res: dict) -> str:
    h, si = res["headline"], res["scenario_inputs"]
    tg = _targeted(res)
    tg_names = [s["segment"] for s in tg]
    low, mid, high = _case(res, "low"), _case(res, "mid"), _case(res, "high")
    drivers = {r["driver"]: r for r in res["yoy"] if r["sort_order"] < 4}
    total = next(r for r in res["yoy"] if r["sort_order"] == 4)
    cust, opc, aov = (
        drivers["Active customers"],
        drivers["Orders per customer"],
        drivers["Net revenue per order"],
    )
    m1 = next(r for r in res["retention_curve"] if r["month_offset"] == 1)
    m12 = next((r for r in res["retention_curve"] if r["month_offset"] == 12), None)
    champ = max(res["segments"], key=lambda s: s["revenue_share"])
    trend = "flat" if abs(h["yoy_growth"]) < 0.03 else ("up" if h["yoy_growth"] > 0 else "down")
    weakest = min(drivers.values(), key=lambda r: r["revenue_effect"])["driver"].lower()
    fx = (
        "\n> **Fixture run. These numbers come from synthetic test data, not the real dataset.**\n"
        if res.get("fixture")
        else ""
    )

    def change(v1: float, v2: float) -> str:
        return f"{(v2 / v1 - 1) * 100:+.1f}%"

    seg_rows = [
        [
            s["segment"],
            _num(s["customers"]),
            pct(s["revenue_share"], 0),
            pct(s["same_season_lapse_rate"], 0),
            gbp(s["revenue_at_risk_next_quarter"]),
        ]
        for s in tg
    ]
    seg_table = _table(
        [
            "Contact these",
            "Customers",
            "Share of revenue",
            "Did not buy last winter",
            "Revenue at risk",
        ],
        seg_rows,
    )
    impact_table = _table(
        [
            "If the campaign lowers their lapse rate by",
            "Revenue protected next quarter",
            "Per customer contacted",
        ],
        [
            [
                f"{pct(r['lapse_reduction'], 0)} (assumed)",
                f"{gbp(r['recovered_revenue_pooled_rates'])} to {gbp(r['recovered_revenue'])}",
                f"£{r['recovered_revenue_per_contact'] * r['recovered_revenue_pooled_rates'] / r['recovered_revenue']:.0f} to £{r['recovered_revenue_per_contact']:.0f}",
            ]
            for r in (low, mid, high)
        ],
    )
    return f"""# Memo: where to spend next quarter's retention budget
{fx}
**To:** Head of Marketing and Finance. **Data:** transactions of a UK online gift-ware retailer, {h["window_start"]} to {h["window_end"]}. Revenue is net of returns and is not profit (the data has no costs).

## The decision
Which customer groups should the December to February retention budget go to, and what happens to revenue if we do nothing?

## Recommendation
Contact the {_num(si["targeted_customers"])} customers in {_join(tg_names)} ({pct(si["targeted_customer_share"], 0)} of identified customers, {pct(si["targeted_revenue_share"], 0)} of their revenue). Skip the other groups: their expected loss per customer is below average. Hold back a random 10% of the contact list so the effect is measured, not assumed.

{seg_table}

## What we found
- **Revenue is {trend}; {weakest} is the weak spot.** Year 2 net revenue is {change(h["net_revenue_year1"], h["net_revenue_year2"])} on year 1 ({gbp(h["net_revenue_year1"])} to {gbp(h["net_revenue_year2"])}). For customers with an ID it moved {_signed_gbp(total["revenue_effect"])}: active customers {_signed_gbp(cust["revenue_effect"])}, orders per customer {_signed_gbp(opc["revenue_effect"])} ({change(opc["year1_value"], opc["year2_value"])}), basket value {_signed_gbp(aov["revenue_effect"])}.
- **Customers come back unevenly.** {pct(h["one_order_share"], 0)} bought only once. Of each new cohort, about {pct(m1["retention_rate"], 0)} buy the next month{f" and {pct(m12['retention_rate'], 0)} buy 12 months later" if m12 else ""}.
- **A few customers carry the business.** The top 10% of customers hold {pct(h["top_decile_revenue_share"], 0)} of revenue. {champ["segment"]} are {pct(champ["customer_share"], 0)} of customers and {pct(champ["revenue_share"], 0)} of revenue, and {pct(champ["same_season_lapse_rate"], 0)} of them did not buy in the same quarter last winter.
- **Doing nothing is not free.** If nothing is done and customers behave as they did last winter, about {gbp(si["total_revenue_at_risk"])} of next quarter's revenue ({pct(si["at_risk_share_of_run_rate"], 0)} of today's quarterly run-rate) is at risk because those customers go quiet; {pct(si["targeted_share_of_at_risk"], 0)} of that sits in the groups above. Expected revenue from today's identified customers is then about {gbp(si["expected_next_q_revenue_do_nothing"])}.

## Expected impact: a scenario, not a result
{impact_table}

The low end uses all-season average lapse rates, the high end last winter's. The lapse reductions of {pct(low["lapse_reduction"], 0)}, {pct(mid["lapse_reduction"], 0)} and {pct(high["lapse_reduction"], 0)} are **assumptions**: nothing in this data measures a campaign. Judge the per-customer figure against what a contact costs and the margin on the sales it protects; we have neither.

## Assumptions and risks
- This winter's lapse rates match last winter's. The 95% interval on the {champ["segment"]} rate is {pct(champ["lapse_ci_low"], 0)} to {pct(champ["lapse_ci_high"], 0)}, but it is one winter, and if that winter was unusual so are the rates.
- Revenue at risk = a segment's quarterly run-rate (last 12 months / 4) times its lapse rate. Guest checkouts ({pct(h["guest_revenue_share"], 0)} of revenue) have no customer ID and are outside this analysis.
- Customers who would have bought anyway can absorb the budget; the hold-out is the safeguard. Many customers are wholesalers (per the dataset's description) and one account is {pct(h["top1_customer_share"], 1)} of all revenue, so a consumer-style offer may fit badly.
"""


def dq_md(res: dict) -> str:
    h = res["headline"]
    out = [
        "# Data quality decisions",
        "",
        "Generated from `dq.rule_log` (see `sql/20_dq_flags.sql` and `sql/22_dq_log.sql`). Each raw row gets one verdict: kept, or removed by the first matching rule below, in this order.",
        "",
        f"Raw rows: {_num(h['raw_rows'])}. Rows kept: {_num(h['kept_rows'])} ({pct(h['kept_rows'] / h['raw_rows'])}).",
        "",
    ]
    rows = []
    for r in res["dq"]:
        rows.append(
            [
                str(r["rule_order"]),
                f"`{r['rule']}`",
                r["kind"].replace("_", " "),
                _num(r["n_rows"]),
                pct(r["share_of_raw_rows"], 2),
                gbp(r["revenue"]) if r["revenue"] is not None else "n/a",
                r["decision"],
            ]
        )
    out.append(
        _table(
            ["#", "Rule", "Action", "Rows", "% of raw", "Revenue affected", "Decision"],
            rows,
            ["r", "l", "l", "r", "r", "r", "l"],
        )
    )
    out += [
        "",
        "Revenue affected is quantity x price on the affected rows. Rules 10 to 13 describe rows that stay in the data; rules 14 to 16 describe normalisation, not removal.",
        "",
        "## Revenue bridge",
        "",
        _table(
            ["Step", "Rows", "Revenue"],
            [
                [
                    b["label"].replace("_", " "),
                    f"{b['n_rows']:+,}" if b["step"] not in (0, 99) else _num(b["n_rows"]),
                    gbp(b["revenue"], 2),
                ]
                for b in res["bridge"]
            ],
        ),
        "",
        "Removing non-merchandise lines raises revenue because most of them (manual adjustments, bank and marketplace fees, bad debt) were negative.",
        "",
    ]
    return "\n".join(out)
